package lexicon.utils;

import org.junit.jupiter.api.extension.BeforeAllCallback;
import org.junit.jupiter.api.extension.ExtensionContext;
import org.springframework.core.io.ClassPathResource;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.stream.Collectors;

/**
 * Prepares the private in-memory test database once per test run (registered automatically through
 * META-INF/services, see build.gradle for why tests never use a real database).
 *
 * In production the shared database already holds the tables that other servers create (players comes from
 * the Alchemy server) and Lexicon's tables are created in an order that only works on an existing database.
 * A brand-new in-memory database needs both created up front.
 */
public class TestDatabaseBootstrap implements BeforeAllCallback {

    private static boolean done;
    /** Held for the whole run so the in-memory database is never dropped between test classes. */
    @SuppressWarnings("unused")
    private static Connection keepAlive;

    @Override
    public void beforeAll(ExtensionContext context) throws Exception {
        synchronized (TestDatabaseBootstrap.class) {
            if (done) {
                return;
            }
            String url = DatabaseConfig.url();
            if (!url.startsWith("jdbc:hsqldb:mem:")) {
                throw new IllegalStateException("Refusing to run tests against a non-memory database: " + url);
            }
            keepAlive = DriverManager.getConnection(url, "SA", DatabaseConfig.password());
            try (Statement stmt = keepAlive.createStatement()) {
                // Same definition the Alchemy server uses; Lexicon only adds columns to it
                stmt.execute("CREATE TABLE IF NOT EXISTS PUBLIC.PLAYERS ("
                        + "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "username VARCHAR(255) NOT NULL UNIQUE, "
                        + "password VARCHAR(255) NOT NULL, "
                        + "level INTEGER DEFAULT 1)");

                String sql;
                try (BufferedReader reader = new BufferedReader(new InputStreamReader(
                        new ClassPathResource("schema.sql").getInputStream(), StandardCharsets.UTF_8))) {
                    sql = reader.lines().collect(Collectors.joining("\n"));
                }
                for (String statement : sql.split(";")) {
                    String trimmed = statement.lines().filter(l -> !l.trim().startsWith("--"))
                            .collect(Collectors.joining("\n")).trim();
                    if (!trimmed.isEmpty()) {
                        try {
                            stmt.execute(trimmed);
                        } catch (Exception ignored) {
                            // a few statements are for other databases; the application skips them as well
                        }
                    }
                }
            }
            done = true;
        }
    }
}
